'use strict';
/*
 * Turns tools/icons.js into Android vector drawables.
 * Colours are left white and tinted at the use site, so one file serves every
 * state the UI needs.
 *   node tools/build-ui-icons.js
 */

const fs = require('fs');
const path = require('path');
const icons = require('./icons');

const OUT = path.join(__dirname, '..', 'mobile', 'app', 'src', 'main', 'res', 'drawable');
fs.mkdirSync(OUT, { recursive: true });

for (const [name, shapes] of Object.entries(icons)) {
  const body = shapes.map((s) => {
    const attrs = ['        android:pathData="' + s.d + '"'];
    if (s.fill) attrs.push('        android:fillColor="#FFFFFFFF"');
    else attrs.push('        android:fillColor="#00000000"');
    if (s.stroke) {
      attrs.push('        android:strokeColor="#FFFFFFFF"');
      attrs.push('        android:strokeWidth="1.7"');
      if (s.cap) attrs.push('        android:strokeLineCap="' + s.cap + '"');
      if (s.join) attrs.push('        android:strokeLineJoin="' + s.join + '"');
    }
    return '    <path\n' + attrs.join('\n') + ' />';
  }).join('\n');

  const xml = '<?xml version="1.0" encoding="utf-8"?>\n' +
    '<!-- Generated by tools/build-ui-icons.js — edit tools/icons.js, not this file. -->\n' +
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n' +
    '    android:width="24dp"\n    android:height="24dp"\n' +
    '    android:viewportWidth="24"\n    android:viewportHeight="24"\n' +
    '    android:tint="?attr/colorControlNormal">\n' + body + '\n</vector>\n';

  fs.writeFileSync(path.join(OUT, name + '.xml'), xml);
}

console.log('wrote ' + Object.keys(icons).length + ' drawables to mobile/.../res/drawable');
